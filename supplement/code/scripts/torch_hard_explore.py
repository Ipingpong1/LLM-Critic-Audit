"""Exploratory checks on the open-model runs on the hard items, beside the Claude runs (free; reads saved rows only).

The prereg lists how stated P(error) changes under "contains an error" and whether replies cite the claim.
The other sections were added after seeing the data, and are marked so in prereg/torch_hard.md.

    .venv/bin/python scripts/torch_hard_explore.py     # writes results/torch_hard/analysis/explore.md

Run pilot.analyze first (see prereg/torch_hard.md): this reads its summary.json for the Δc table.
"""
import csv
import json
import re
import statistics as st
import sys
from collections import Counter
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from stage_c_explore import calibration, tone_diffs  # noqa: E402

T, C = "results/torch_hard", "results/frontier/stage_c"
OPEN = [("qwen3.5_4b", "qwen 4b"), ("qwen3.5_9b", "qwen 9b"), ("gemma4_12b", "gemma 12b"), ("qwen3.5_27b", "qwen 27b")]
FILES = {f"{name} off": f"{T}/{stem}-nothink-bf16-t1.jsonl" for stem, name in OPEN}
FILES |= {f"{name} on": f"{T}/{stem}-think-bf16-t1.jsonl" for stem, name in OPEN}
FILES |= {"haiku off": f"{C}/haiku-5.5-nothink.jsonl", "sonnet off": f"{C}/sonnet-5.5-nothink.jsonl",
          "haiku on": f"{C}/haiku-5.5-think.jsonl", "sonnet on": f"{C}/sonnet-5.5-think.jsonl",
          "opus on": f"{C}/opus-5.5-think.jsonl", "sonnet max": f"{C}/sonnet-5.5-think-max.jsonl"}
SUMMARY_NAME = {f"{name} off": f"{stem.replace('_', ':')}-nothink-bf16-t1" for stem, name in OPEN}
SUMMARY_NAME |= {f"{name} on": f"{stem.replace('_', ':')}-think-bf16-t1" for stem, name in OPEN}
SUMMARY_NAME |= {"haiku off": "haiku-5.5-nothink", "sonnet off": "sonnet-5.5-nothink", "haiku on": "haiku-5.5-think",
                 "sonnet on": "sonnet-5.5-think", "opus on": "opus-5.5-think", "sonnet max": "sonnet-5.5-think-max"}
RATE = re.compile(r"\b90\s?%|90 percent|base rate|ninety", re.I)
CLAIM = re.compile(r"contains an error|(prompt|instruction|user|told)\W+(\w+\W+){0,6}(error|mistake|flaw)", re.I)


def main():
    items = {json.loads(l)["id"]: json.loads(l) for l in open("data/items_hard.jsonl")}
    rows = {k: [json.loads(l) for l in open(p)] for k, p in FILES.items()}
    key = {k: {(r["condition"], r["item_id"]): r for r in rs} for k, rs in rows.items()}
    correct = sorted(i for i, x in items.items() if not x["has_error"])
    thinking = [k for k in rows if k.endswith(("on", "max"))]
    open_on = [f"{n} on" for _, n in OPEN]

    def flips(k, cond, base):
        return {i for i in correct if key[k].get((base, i), {}).get("verdict") == "correct"
                and key[k].get((cond, i), {}).get("verdict") == "error"}

    out = ["# Open models on the hard items: exploratory checks", "",
           "Generated by `scripts/torch_hard_explore.py` from the saved replies. Exploratory and uncorrected for multiple "
           "comparisons. Open models return their full reasoning; Claude returns summaries, so text counts do not compare "
           "across the two.", ""]

    out += ['## "Contains an error": correct solutions (100)', "",
            "| critic | false alarms: neutral → told | stated P(error), median: neutral → told | mean: neutral → told "
            "| flagged only when told |", "|---|---|---|---|---|"]
    for k in rows:
        side = {c: [key[k][(c, i)] for i in correct if (c, i) in key[k]] for c in ("neutral", "presuppose")}
        fa = {c: sum(r["verdict"] == "error" for r in v) for c, v in side.items()}
        ps = {c: [r["p_error"] for r in v if r["p_error"] is not None] for c, v in side.items()}
        out.append(f"| {k} | {fa['neutral']} → {fa['presuppose']} | {st.median(ps['neutral']):.0f} → {st.median(ps['presuppose']):.0f} "
                   f"| {np.mean(ps['neutral']):.0f} → {np.mean(ps['presuppose']):.0f} | {len(flips(k, 'presuppose', 'neutral'))} |")

    out += ["", '## "Contains an error": difference in c − c(neutral), paired over items (2,000 resamples)', "",
            "| critics | difference [95% CI] |", "|---|---|"]
    out += tone_diffs(rows, items, [("qwen 27b on", "opus on"), ("qwen 27b on", "qwen 27b off"), ("qwen 27b on", "qwen 4b on"),
                                    ("qwen 27b on", "qwen 9b on"), ("qwen 27b on", "gemma 12b on"), ("qwen 27b on", "sonnet on"),
                                    ("qwen 9b on", "qwen 9b off"), ("qwen 4b on", "qwen 4b off"), ("gemma 12b on", "gemma 12b off")])

    out += ["", "## Do critics flip the same correct solutions?", "",
            'Flip: passed at neutral, flagged under "contains an error". Items both critics passed at neutral; chance from '
            "10,000 permutations; one-sided p, uncorrected.", "",
            "| critics | items | flips | shared | chance | p |", "|---|---|---|---|---|---|"]
    rng = np.random.default_rng(0)
    for a, b in [("qwen 27b on", "opus on"), ("qwen 4b on", "opus on"), ("qwen 4b on", "qwen 27b on"), ("sonnet on", "opus on"),
                 ("sonnet on", "qwen 27b on"), ("qwen 9b on", "opus on"), ("gemma 12b on", "opus on")]:
        pool = [i for i in correct if key[a].get(("neutral", i), {}).get("verdict") == "correct"
                and key[b].get(("neutral", i), {}).get("verdict") == "correct"]
        fa = np.array([i in flips(a, "presuppose", "neutral") for i in pool])
        fb = np.array([i in flips(b, "presuppose", "neutral") for i in pool])
        sims = np.array([(rng.permutation(fa) & fb).sum() for _ in range(10000)])
        obs = (fa & fb).sum()
        out.append(f"| {a} & {b} | {len(pool)} | {fa.sum()}, {fb.sum()} | {obs} | {sims.mean():.1f} | {(sims >= obs).mean():.3f} |")

    coded = list(csv.DictReader(open(f"{T}/analysis/flips_27b_coded.csv")))
    n = Counter(r["claim_as_reason"] for r in coded)
    out += ["", '## qwen 27b, thinking on: does the reasoning use the claim as a reason?', "",
            f"All {len(coded)} flips, coded from excerpts by one reader who knew the results and the condition, so a rough guide "
            f"(`results/torch_hard/analysis/flips_27b_coded.csv`): {n['clear']} clearly use it, {n['soft']} in softer terms, "
            f"{n['none']} not in the excerpts read.", ""]
    k = "qwen 27b on"
    flip_ids = flips(k, "presuppose", "neutral")
    passed = [i for i in correct if key[k].get(("presuppose", i), {}).get("verdict") == "correct"]
    mention = lambda ids: sum(bool(CLAIM.search(key[k][("presuppose", i)].get("reasoning") or "")) for i in ids)
    out += [f"Merely mentioning the claim does not separate them: a text search finds it in {mention(flip_ids)} of {len(flip_ids)} "
            f"flips and {mention(passed)} of {len(passed)} correct solutions it still passed. The reasoning shows how the flips "
            "are argued, not why these items flipped.", ""]

    out += ["## Which way the stated base rate moves verdicts", "",
            "Correct solutions passed when told 50% and flagged when told 90%, and flags dropped when told 10% (correct "
            "solutions only).", "",
            "| critic | false alarms: 10% / 50% / 90% | hits: 10% / 50% / 90% | flagged, told 90% | median P(error) at 50% for those "
            "| dropped, told 10% |", "|---|---|---|---|---|---|"]
    flawed = [i for i, x in items.items() if x["has_error"]]
    for k in rows:
        count = lambda ids, c: sum(key[k][(c, i)]["verdict"] == "error" for i in ids if (c, i) in key[k])
        up = flips(k, "br90", "br50")
        down = [i for i in correct if key[k][("br50", i)]["verdict"] == "error" and key[k][("br10", i)]["verdict"] == "correct"]
        p = [key[k][("br50", i)]["p_error"] for i in up if key[k][("br50", i)]["p_error"] is not None]
        out.append(f"| {k} | {count(correct, 'br10')} / {count(correct, 'br50')} / {count(correct, 'br90')} "
                   f"| {count(flawed, 'br10')} / {count(flawed, 'br50')} / {count(flawed, 'br90')} "
                   f"| {len(up)} | {st.median(p) if p else 0:.0f} | {len(down)} |")

    out += ["", "## Does the reasoning name the rate? (told 90%, correct solutions, thinking on)", "",
            "| critic | flipped: names it / all | still passed: names it / all |", "|---|---|---|"]
    for k in open_on:
        up = flips(k, "br90", "br50")
        passed = [i for i in correct if key[k].get(("br90", i), {}).get("verdict") == "correct"]
        g = lambda ids: sum(bool(RATE.search(key[k][("br90", i)].get("reasoning") or "")) for i in ids)
        out.append(f"| {k} | {g(up)} / {len(up)} | {g(passed)} / {len(passed)} |")

    out += ["", "## Calibration when told 50%: mean stated P(error) vs % actually flawed", ""]
    out += calibration({k: rows[k] for k in thinking}, items)

    summ = {m["model"]: m for m in json.load(open(f"{T}/analysis/summary.json"))}
    out += ["", "## ρ's two parts", "",
            "ρ = Δc ÷ (ln 81 / d′). A larger d′ shrinks the benchmark, so ρ can rise with no larger shift in c.", "",
            "| critic | Δc observed [95% CI] | ideal Δc | ρ | z-ROC slope at 50% |", "|---|---|---|---|---|"]
    for k in rows:
        m = summ[SUMMARY_NAME[k]]
        out.append(f"| {k} | {m['delta_c']:.2f} [{m['delta_c_ci'][0]:.2f}, {m['delta_c_ci'][1]:.2f}] | {m['ideal_delta_c']:.2f} "
                   f"| {m['rho']:.3f} | {m['zroc_slope_ref']:.2f} |")

    Path(f"{T}/analysis/explore.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
