"""Exploratory checks on the Stage C replies (not pre-registered; free, reads saved rows only).

  1. How often a thinking summary came back, per critic: "thinking on" is adaptive, so the model decides.
  2. How often a reply names the stated rate, with the neutral condition as a control.
  3. "Contains an error": correct solutions flagged there but passed at neutral, the confidence stated,
     and a rough text search for replies that say they found nothing or point at the prompt's claim.
  4. Paired item-bootstrap differences in the "contains an error" shift between critics.
  5. Calibration of the stated P(error) when told 50%, which the Bayes check takes at face value.

The text search is a crude regular expression, so its counts are a rough guide, not a measurement.
"""
import argparse
import json
import re
import statistics as st
from pathlib import Path

import numpy as np
from scipy.stats import norm

CRITICS = ["haiku-5.5-nothink", "haiku-5.5-think", "sonnet-5.5-nothink", "sonnet-5.5-think",
           "opus-5.5-think", "sonnet-5.5-think-max"]
RATE = {"neutral": r"\b(10|90)\s?%|base rate|calibration", "br10": r"\b10\s?%|base rate|calibration",
        "br90": r"\b90\s?%|base rate|calibration"}
FOUND_NOTHING = re.compile(
    r"(could not|couldn.t|can.t|cannot|did not|didn.t|unable to|fail(ed)? to|no|not) (\w+ ){0,3}"
    r"(find|found|locate|identify|spot|see)\b|no (\w+ ){0,3}(mistake|error|flaw)s? (\w+ ){0,2}(found|apparent|visible)"
    r"|found no|every step (checks|holds|is correct)|appears? (fully )?correct", re.I)
PREMISE = re.compile(
    r"(prompt|task|instruction|statement|system|note|premise|you|user|told|says|said|claims?|asserts?|stated)"
    r"\W+(\w+\W+){0,6}(error|mistake|flaw)|(given|told|assured|asserted|presuppos\w*)\W+(\w+\W+){0,6}(error|mistake)"
    r"|contains an error", re.I)


def text(r):
    return (r.get("reasoning") or "") + " " + (r.get("raw") or "")


def tone_diffs(rows, items, pairs, n_boot=2000, seed=0):
    """c(presuppose) - c(neutral), paired over items; same item resamples for every critic."""
    ids = sorted(items)
    fl = np.array([i for i, x in enumerate(ids) if items[x]["has_error"]])
    co = np.array([i for i, x in enumerate(ids) if not items[x]["has_error"]])
    err = {}
    for c, rs in rows.items():
        k = {(r["condition"], r["item_id"]): r["verdict"] for r in rs}
        for cond in ("neutral", "presuppose"):
            v = [k.get((cond, x)) for x in ids]
            err[c, cond] = (np.array([x == "error" for x in v], float), np.array([x in ("error", "correct") for x in v], float))

    def shift(c, f, g):
        out = 0.0
        for cond, sign in (("presuppose", 1), ("neutral", -1)):
            e, ok = err[c, cond]
            h = (e[f].sum(-1) + 0.5) / (ok[f].sum(-1) + 1)
            a = (e[g].sum(-1) + 0.5) / (ok[g].sum(-1) + 1)
            out = out + sign * -(norm.ppf(h) + norm.ppf(a)) / 2
        return out

    rng = np.random.default_rng(seed)
    bf = rng.choice(fl, (n_boot, len(fl)))
    bc = rng.choice(co, (n_boot, len(co)))
    lines = []
    for a, b in pairs:
        d = shift(a, fl, co) - shift(b, fl, co)
        lo, hi = np.percentile(shift(a, bf, bc) - shift(b, bf, bc), [2.5, 97.5])
        lines.append(f"| {a} − {b} | {d:+.2f} [{lo:.2f}, {hi:.2f}] |")
    return lines


def calibration(rows, items):
    bins = [(0, 10), (10, 50), (50, 90), (90, 100)]
    head = "| critic | " + " | ".join(f"{a} < p ≤ {b}" if a else f"p ≤ {b}" for a, b in bins) + " |"
    lines = [head, "|---|" + "---|" * len(bins)]
    for c, rs in rows.items():
        cells = []
        for a, b in bins:
            sel = [r for r in rs if r["condition"] == "br50" and r["p_error"] is not None
                   and (a < r["p_error"] <= b or (a == 0 and r["p_error"] == 0))]
            if sel:
                truth = 100 * sum(bool(items[r["item_id"]]["has_error"]) for r in sel) / len(sel)
                cells.append(f"{st.mean(r['p_error'] for r in sel):.0f} vs {truth:.0f} (n={len(sel)})")
            else:
                cells.append("–")
        lines.append(f"| {c} | " + " | ".join(cells) + " |")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="results/frontier/stage_c")
    ap.add_argument("--items", default="data/items_hard.jsonl")
    ap.add_argument("--out", default="results/frontier/stage_c/analysis/explore.md")
    args = ap.parse_args()
    items = {json.loads(l)["id"]: json.loads(l) for l in open(args.items)}
    rows = {c: [json.loads(l) for l in open(Path(args.dir) / f"{c}.jsonl")] for c in CRITICS}
    out = ["# Stage C exploratory checks", "",
           "Not pre-registered. Generated by `scripts/stage_c_explore.py` from the saved replies.", "",
           "## Thinking summaries returned", "",
           "| critic | replies with a summary | median output tokens, with / without |", "|---|---|---|"]
    for c, rs in rows.items():
        w = [r["completion_tokens"] for r in rs if r.get("reasoning")]
        wo = [r["completion_tokens"] for r in rs if not r.get("reasoning")]
        out.append(f"| {c} | {100 * len(w) / len(rs):.0f}% | {st.median(w) if w else 0:.0f} / {st.median(wo) if wo else 0:.0f} |")
    out += ["", "## Replies naming the stated rate (of 200 per condition)", "",
            "Counts the summary plus the visible reply. Many replies are bare JSON, and a summary may leave things out, "
            "so a low count does not show the rate went unused. The neutral row shows how often these strings turn up "
            "anyway, for example as percentages in the math problems.", "",
            "| critic | neutral | told 10% | told 90% |", "|---|---|---|---|"]
    for c, rs in rows.items():
        n = [sum(bool(re.search(p, text(r), re.I)) for r in rs if r["condition"] == cond) for cond, p in RATE.items()]
        out.append(f"| {c} | {n[0]} | {n[1]} | {n[2]} |")
    out += ["", '## "Contains an error": correct solutions', "",
            "| critic | false alarms: neutral → told | median stated P(error): neutral → told | flagged only when told "
            "| with text | says it found nothing or cites the claim (rough) |", "|---|---|---|---|---|---|"]
    for c, rs in rows.items():
        k = {(r["condition"], r["item_id"]): r for r in rs}
        side = {cond: [r for (cc, i), r in k.items() if cc == cond and not items[i]["has_error"]]
                for cond in ("neutral", "presuppose")}
        fa = {cond: sum(r["verdict"] == "error" for r in v) for cond, v in side.items()}
        med = {cond: st.median(r["p_error"] for r in v if r["p_error"] is not None) for cond, v in side.items()}
        flips = [r for r in side["presuppose"] if r["verdict"] == "error"
                 and k[("neutral", r["item_id"])]["verdict"] == "correct"]
        wt = [text(r) for r in flips if len(text(r).strip()) > 60]
        hit = sum(bool(FOUND_NOTHING.search(t) or PREMISE.search(t)) for t in wt)
        out.append(f"| {c} | {fa['neutral']} → {fa['presuppose']} | {med['neutral']:.0f} → {med['presuppose']:.0f} "
                   f"| {len(flips)} | {len(wt)} | {hit} |")
    out += ["", '## "Contains an error": difference in c − c(neutral), paired over items (2,000 resamples)', "",
            "| critics | difference [95% CI] |", "|---|---|"]
    out += tone_diffs(rows, items, [("opus-5.5-think", "sonnet-5.5-think"), ("opus-5.5-think", "haiku-5.5-think"),
                                    ("sonnet-5.5-think", "haiku-5.5-think"), ("sonnet-5.5-think", "sonnet-5.5-nothink"),
                                    ("sonnet-5.5-think-max", "sonnet-5.5-think")])
    out += ["", "## Calibration when told 50%: mean stated P(error) vs % actually flawed", "",
            "The Bayes check reads the stated value as a posterior, so it leans on these being about right, "
            "above all in the middle bins.", ""]
    out += calibration(rows, items)
    Path(args.out).write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
